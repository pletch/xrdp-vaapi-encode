/* monitors by name: output-management heads create them; wl_outputs,
   which exist only while an output is enabled, attach to them */
static struct wlr_mon *
mon_by_name(struct wlr *b, const char *name, int create)
{
    int i;

    for (i = 0; i < b->num_mons; i++)
    {
        if (strcmp(b->mons[i].name, name) == 0)
        {
            return b->mons + i;
        }
    }
    if (!create || b->num_mons >= MAX_MONS)
    {
        return NULL;
    }
    i = b->num_mons++;
    snprintf(b->mons[i].name, sizeof(b->mons[i].name), "%s", name);
    return b->mons + i;
}

