/*****************************************************************************/
/* One capture buffer. GPU path: a single-plane XRGB8888 dma-buf, shared by
   the compositor (wl_buffer) and the helper (EGLImage); tiled modifiers
   first, as they capture faster than LINEAR. CPU path: shared memory. */
static int
alloc_buf(struct wlr_mon *m, struct buf *bf, int index)
{
    static const uint64_t pref[] =
    {
        I915_FORMAT_MOD_Y_TILED, I915_FORMAT_MOD_X_TILED, DRM_FORMAT_MOD_LINEAR
    };
    struct wlr *b = m->b;
    struct zwp_linux_buffer_params_v1 *params;
    uint64_t mod;
    uint32_t stride;
    uint32_t offset;
    int p;
    int i;

    if (b->wl_shm)
    {
        /* CPU path: the compositor copies into shared memory we read */
        struct wl_shm_pool *pool;
        int fd;

        bf->shm_stride = m->width * 4;
        bf->shm_bytes = (size_t) bf->shm_stride * m->height;
        fd = memfd_create("wlxrdp-capture", MFD_CLOEXEC);
        if (fd < 0 || ftruncate(fd, bf->shm_bytes) != 0)
        {
            if (fd >= 0)
            {
                close(fd);
            }
            return 1;
        }
        bf->shm = mmap(NULL, bf->shm_bytes, PROT_READ | PROT_WRITE,
                       MAP_SHARED, fd, 0);
        if (bf->shm == MAP_FAILED)
        {
            bf->shm = NULL;
            close(fd);
            return 1;
        }
        pool = wl_shm_create_pool(b->shm, fd, bf->shm_bytes);
        bf->wl_buffer = wl_shm_pool_create_buffer(pool, 0, m->width,
                        m->height, bf->shm_stride, m->shm_format);
        wl_shm_pool_destroy(pool);
        close(fd);
        LOG(LOG_LEVEL_INFO, "monitor %d buffer %d: %dx%d shm (CPU path)",
            m->index, index, m->width, m->height);
        return 0;
    }

    bf->bo = NULL;
    /* preferred modifiers in order, then anything else offered */
    for (p = 0; p <= (int) (sizeof(pref) / sizeof(pref[0])) &&
            bf->bo == NULL; p++)
    {
        for (i = 0; i < m->num_mods && bf->bo == NULL; i++)
        {
            if (m->mods[i] == DRM_FORMAT_MOD_INVALID)
            {
                continue;
            }
            if (p < (int) (sizeof(pref) / sizeof(pref[0])) &&
                    m->mods[i] != pref[p])
            {
                continue;
            }
            bf->bo = gbm_bo_create_with_modifiers2(b->gbm, m->width,
                                                   m->height,
                                                   DRM_FORMAT_XRGB8888,
                                                   m->mods + i, 1,
                                                   GBM_BO_USE_RENDERING);
            if (bf->bo != NULL && gbm_bo_get_plane_count(bf->bo) != 1)
            {
                gbm_bo_destroy(bf->bo);
                bf->bo = NULL;
            }
        }
    }
    if (bf->bo == NULL)
    {
        LOG(LOG_LEVEL_ERROR, "no single-plane XRGB8888 modifier allocates");
        return 1;
    }
    mod = gbm_bo_get_modifier(bf->bo);
    stride = gbm_bo_get_stride_for_plane(bf->bo, 0);
    offset = gbm_bo_get_offset(bf->bo, 0);
    bf->fd = gbm_bo_get_fd_for_plane(bf->bo, 0);
    if (bf->fd < 0)
    {
        /* free_buf() releases the buffer object */
        LOG(LOG_LEVEL_ERROR, "monitor %d buffer %d: no dma-buf fd for the "
            "buffer object", m->index, index);
        return 1;
    }
    LOG(LOG_LEVEL_INFO, "monitor %d buffer %d: %dx%d modifier 0x%016llx",
        m->index, index, m->width, m->height, (unsigned long long) mod);

    params = zwp_linux_dmabuf_v1_create_params(b->dmabuf);
    zwp_linux_buffer_params_v1_add(params, bf->fd, 0, offset, stride,
                                   mod >> 32, mod & 0xffffffff);
    bf->wl_buffer = zwp_linux_buffer_params_v1_create_immed(
                        params, m->width, m->height, DRM_FORMAT_XRGB8888, 0);
    zwp_linux_buffer_params_v1_destroy(params);
    bf->stride = stride;
    bf->offset = offset;
    bf->modifier = mod;
    return 0;
}

/*****************************************************************************/
static void
free_buf(struct buf *bf)
{
    if (bf->shm != NULL)
    {
        munmap(bf->shm, bf->shm_bytes);
        bf->shm = NULL;
    }
    if (bf->wl_buffer != NULL)
    {
        wl_buffer_destroy(bf->wl_buffer);
        bf->wl_buffer = NULL;
    }
    if (bf->bo != NULL)
    {
        gbm_bo_destroy(bf->bo);
        bf->bo = NULL;
    }
    if (bf->fd >= 0)
    {
        close(bf->fd);
        bf->fd = -1;
    }
}

/*****************************************************************************/
/* the wlroots adapter: capture a frame the core wants, into a buffer the
   core does not hold, when the session can take a request */
static void
request_frame(struct wlr_mon *m)
{
    int index;

    if (!m->wanted || m->session == NULL || m->frame != NULL ||
            m->stopped || m->constraints_changed)
    {
        return;
    }
    for (index = 0; index < NUM_BUFS && m->bufs[index].held; index++)
    {
    }
    if (index == NUM_BUFS)
    {
        return; /* all held: a release retries */
    }
    m->cur = index;
    m->num_rects = 0;
    m->frame_state = 1;
    m->request_ms = now_ms32();
    m->frame = ext_image_copy_capture_session_v1_create_frame(m->session);
    ext_image_copy_capture_frame_v1_add_listener(m->frame, &g_frame_listener,
            m);
    ext_image_copy_capture_frame_v1_attach_buffer(m->frame,
            m->bufs[index].wl_buffer);
    /* whole buffer stale: the compositor copies the full frame, so each
       buffer is complete (AVC444's aux pass needs that) */
    ext_image_copy_capture_frame_v1_damage_buffer(m->frame, 0, 0,
            m->width, m->height);
    ext_image_copy_capture_frame_v1_capture(m->frame);
}


