/* the keymap goes to the compositor as a memfd */
static int
wlr_keymap(void *a, const char *text)
{
    struct wlr *b = a;
    size_t len = strlen(text) + 1;
    int rv = 1;
    int fd;
    void *p;

    if (b->vkbd == NULL)
    {
        return 1;
    }
    fd = memfd_create("wlxrdp-keymap", MFD_CLOEXEC);
    if (fd >= 0 && ftruncate(fd, len) == 0)
    {
        p = mmap(NULL, len, PROT_READ | PROT_WRITE, MAP_SHARED, fd, 0);
        if (p != MAP_FAILED)
        {
            memcpy(p, text, len);
            munmap(p, len);
            zwp_virtual_keyboard_v1_keymap(b->vkbd,
                                           WL_KEYBOARD_KEYMAP_FORMAT_XKB_V1,
                                           fd, len);
            rv = 0;
        }
    }
    if (fd >= 0)
    {
        close(fd);
    }
    return rv;
}

static void
wlr_motion(void *a, int x, int y, int width, int height)
{
    struct wlr *b = a;
    struct wlr_mon *m = NULL;
    int64_t best = -1;
    int ext_w = 0;
    int ext_h = 0;
    double lx;
    double ly;
    int i;

    if (b->vptr == NULL)
    {
        return;
    }
    /* the monitor under (x, y) in layout pixels, or the nearest; and the
       logical layout's extent, which the compositor maps absolute
       positions onto */
    for (i = 0; i < b->active; i++)
    {
        struct wlr_mon *o = b->mons + i;
        int64_t dx = x < o->x ? o->x - x : x >= o->x + o->want_w
                     ? x - (o->x + o->want_w - 1) : 0;
        int64_t dy = y < o->y ? o->y - y : y >= o->y + o->want_h
                     ? y - (o->y + o->want_h - 1) : 0;

        if (best < 0 || dx * dx + dy * dy < best)
        {
            best = dx * dx + dy * dy;
            m = o;
        }
        ext_w = o->lx + o->lw > ext_w ? o->lx + o->lw : ext_w;
        ext_h = o->ly + o->lh > ext_h ? o->ly + o->lh : ext_h;
    }
    if (m == NULL || ext_w <= 0 || ext_h <= 0)
    {
        zwlr_virtual_pointer_v1_motion_absolute(b->vptr, now_ms32(), x, y,
                                                width, height);
        zwlr_virtual_pointer_v1_frame(b->vptr);
        return;
    }
    x = x < m->x ? m->x : x >= m->x + m->want_w ? m->x + m->want_w - 1 : x;
    y = y < m->y ? m->y : y >= m->y + m->want_h ? m->y + m->want_h - 1 : y;
    lx = m->lx + (x - m->x) * 100.0 / m->scale;
    ly = m->ly + (y - m->y) * 100.0 / m->scale;
    /* in 1/16ths of a logical pixel, so a scaled monitor keeps every
       client pixel */
    zwlr_virtual_pointer_v1_motion_absolute(
        b->vptr, now_ms32(), (uint32_t) lround(lx * 16),
        (uint32_t) lround(ly * 16), (uint32_t) ext_w * 16,
        (uint32_t) ext_h * 16);
    zwlr_virtual_pointer_v1_frame(b->vptr);
}

static void
wlr_button(void *a, int button, int down)
{
    struct wlr *b = a;

    if (b->vptr != NULL)
    {
        zwlr_virtual_pointer_v1_button(b->vptr, now_ms32(), button,
                                       down ? WL_POINTER_BUTTON_STATE_PRESSED
                                       : WL_POINTER_BUTTON_STATE_RELEASED);
        zwlr_virtual_pointer_v1_frame(b->vptr);
    }
}

static void
wlr_scroll(void *a, enum wla_axis axis, int discrete, double value)
{
    struct wlr *b = a;
    uint32_t wl_axis = axis == WLA_AXIS_HORIZONTAL
                       ? WL_POINTER_AXIS_HORIZONTAL_SCROLL
                       : WL_POINTER_AXIS_VERTICAL_SCROLL;

    if (b->vptr == NULL)
    {
        return;
    }
    /* The source goes after the axis event, as the protocol allows (any
       time before the frame): wlroots applies it to the axis last named,
       so sent first it lands on the other axis after an axis change. */
    if (discrete != 0)
    {
        zwlr_virtual_pointer_v1_axis_discrete(b->vptr, now_ms32(), wl_axis,
                                              wl_fixed_from_double(value),
                                              discrete);
        zwlr_virtual_pointer_v1_axis_source(b->vptr,
                                            WL_POINTER_AXIS_SOURCE_WHEEL);
    }
    else
    {
        zwlr_virtual_pointer_v1_axis(b->vptr, now_ms32(), wl_axis,
                                     wl_fixed_from_double(value));
        zwlr_virtual_pointer_v1_axis_source(b->vptr,
                                            WL_POINTER_AXIS_SOURCE_CONTINUOUS);
    }
    zwlr_virtual_pointer_v1_frame(b->vptr);
}



/*****************************************************************************/
/* capture lifecycle */

static int
capture_start(struct wlr_mon *m)
{
    struct wlr *b = m->b;
    struct ext_image_capture_source_v1 *source;
    struct wla_buffer wb[NUM_BUFS];
    int i;

    if (m->output == NULL)
    {
        LOG(LOG_LEVEL_ERROR, "monitor %d (%s): no output to capture",
            m->index, m->name);
        return 1;
    }
    m->constraints_done = 0;
    m->stopped = 0;
    m->have_xrgb = 0;
    m->shm_format = 0;
    source = ext_output_image_capture_source_manager_v1_create_source(
                 b->source_mgr, m->output);
    m->session = ext_image_copy_capture_manager_v1_create_session(
                     b->copy_mgr, source, 0 /* cursor not painted */);
    ext_image_capture_source_v1_destroy(source);
    ext_image_copy_capture_session_v1_add_listener(m->session,
            &g_session_listener, m);
    while (!m->constraints_done && !m->stopped)
    {
        if (wl_display_dispatch(b->display) < 0)
        {
            return 1;
        }
    }
    if (m->stopped || (b->wl_shm ? m->shm_format == 0 : !m->have_xrgb))
    {
        LOG(LOG_LEVEL_ERROR, "monitor %d: capture session unusable",
            m->index);
        return 1;
    }
    LOG(LOG_LEVEL_INFO, "monitor %d: capturing %s at %dx%d", m->index,
        m->name, m->width, m->height);
    for (i = 0; i < NUM_BUFS; i++)
    {
        struct wla_buffer *w = wb + i;

        if (alloc_buf(m, m->bufs + i, i) != 0)
        {
            return 1;
        }
        m->bufs[i].held = 0;
        memset(w, 0, sizeof(*w));
        w->width = m->width;
        w->height = m->height;
        w->fourcc = !b->wl_shm || m->shm_format == WL_SHM_FORMAT_XRGB8888
                    ? DRM_FORMAT_XRGB8888 : DRM_FORMAT_XBGR8888;
        w->fd = m->bufs[i].fd;
        w->stride = m->bufs[i].stride;
        w->offset = m->bufs[i].offset;
        w->modifier = m->bufs[i].modifier;
        w->shm = m->bufs[i].shm;
        w->shm_stride = m->bufs[i].shm_stride;
    }
    b->ev->buffers(b->core, m->index, NUM_BUFS, wb);
    m->last_ready = -1;
    m->alloc_w = m->width;
    m->alloc_h = m->height;
    m->constraints_changed = 0;
    m->capture_ms = now_ms32();
    m->wanted = 0;
    cursor_start(m);
    return 0;
}

/*****************************************************************************/
static void
capture_stop(struct wlr_mon *m)
{
    int i;

    cursor_stop(m);
    if (m->frame != NULL)
    {
        ext_image_copy_capture_frame_v1_destroy(m->frame);
        m->frame = NULL;
    }
    if (m->session != NULL)
    {
        ext_image_copy_capture_session_v1_destroy(m->session);
        m->session = NULL;
    }
    for (i = 0; i < NUM_BUFS; i++)
    {
        free_buf(m->bufs + i);
    }
    m->last_ready = -1;
    m->frame_state = 0;
    m->alloc_w = 0;
    m->alloc_h = 0;
    m->wanted = 0;
    m->b->ev->buffers(m->b->core, m->index, 0, NULL);
}

/*****************************************************************************/
/* Capture every monitor in the layout. */
static int
capture_start_all(struct wlr *b)
{
    int rv = 0;
    int i;

    for (i = 0; i < b->num_mons; i++)
    {
        b->mons[i].retries = 0;
        if (b->mons[i].enabled && capture_start(b->mons + i) != 0)
        {
            capture_stop(b->mons + i);
            rv = 1;
        }
    }
    return rv;
}

/*****************************************************************************/
static void
capture_stop_all(struct wlr *b)
{
    int i;

    for (i = 0; i < b->num_mons; i++)
    {
        capture_stop(b->mons + i);
    }
    wl_display_roundtrip(b->display);
}

/*****************************************************************************/
/* One monitor's capture again, e.g. after its output changed size. */
static void
capture_restart(struct wlr_mon *m)
{
    capture_stop(m);
    wl_display_roundtrip(m->b->display);
    if (capture_start(m) != 0)
    {
        /* nothing captured: wlr_capture_dispatch retries it */
        capture_stop(m);
        m->retries++;
        m->retry_ms = now_ms32();
        LOG(LOG_LEVEL_WARNING, "monitor %d: capture did not restart "
            "(attempt %d of %d)", m->index, m->retries, CAPTURE_RETRIES);
        return;
    }
    m->retries = 0; /* the core resends the helper's batch */
}

/*****************************************************************************/
/* a capture completed: hand it to the core */
static void
on_frame_done(struct wlr_mon *m)
{
    int state = m->frame_state;

    ext_image_copy_capture_frame_v1_destroy(m->frame);
    m->frame = NULL;
    m->frame_state = 0;
    if (state == 3)
    {
        return; /* failed: the next request retries */
    }
    m->last_ready = m->cur;
    m->bufs[m->cur].held = 1;
    m->wanted = 0;
    m->b->ev->frame(m->b->core, m->index, m->cur, m->rects, m->num_rects);
}

/*****************************************************************************/
/* The wlroots adapter's capture ops (wla_ops) and its part of the loop */

static int
wlr_start(void *a, enum wla_mode mode)
{
    struct wlr *b = a;

    b->wl_shm = mode == WLA_SHM;
    b->capturing = 1;
    return capture_start_all(b);
}

static void
wlr_stop(void *a)
{
    struct wlr *b = a;

    b->capturing = 0;
    capture_stop_all(b);
}

static void
wlr_want_frame(void *a, int mon)
{
    struct wlr *b = a;

    if (mon >= 0 && mon < b->num_mons)
    {
        b->mons[mon].wanted = 1;
        request_frame(b->mons + mon);
    }
}

static void
wlr_release(void *a, int mon, int buf)
{
    struct wlr *b = a;

    if (mon >= 0 && mon < b->num_mons && buf >= 0 && buf < NUM_BUFS)
    {
        b->mons[mon].bufs[buf].held = 0;
        request_frame(b->mons + mon); /* one may be waiting for a buffer */
    }
}

/* After Wayland events: finished captures, and the capture watchdogs */
static void
wlr_capture_dispatch(struct wlr *b)
{
    int i;

    for (i = 0; i < b->num_mons; i++)
    {
        struct wlr_mon *m = b->mons + i;

        if (m->frame != NULL && m->frame_state >= 2)
        {
            on_frame_done(m);
        }
        if (m->session == NULL)
        {
            if (b->capturing && m->enabled && m->retries > 0 &&
                    now_ms32() - m->retry_ms >= CAPTURE_RETRY_MS)
            {
                if (m->retries >= CAPTURE_RETRIES)
                {
                    b->ev->lost(b->core, "a monitor's capture could not be "
                                "restarted");
                    return;
                }
                capture_restart(m);
                m->wanted = 1;
                request_frame(m);
            }
            continue;
        }
        if (m->stopped)
        {
            LOG(LOG_LEVEL_WARNING, "monitor %d: capture session "
                "stopped, restarting", m->index);
            capture_restart(m);
        }
        else if (m->constraints_changed)
        {
            /* the compositor changed the output's size itself (not a
               client resize): capture at the new size. xrdp's surface is
               still the client's size, so this only keeps the session
               alive until the client resizes. */
            LOG(LOG_LEVEL_WARNING, "monitor %d: capture constraints "
                "changed to %dx%d, restarting capture", m->index,
                m->width, m->height);
            capture_restart(m);
        }
        else if (m->last_ready < 0 && m->frame != NULL &&
                 now_ms32() - m->request_ms >= FIRST_FRAME_MS)
        {
            /* a new session delivers its first frame at once: this one is
               stuck (no clock runs while no frame is wanted) */
            LOG(LOG_LEVEL_WARNING, "monitor %d: no first frame %d ms after "
                "asking, restarting capture", m->index, FIRST_FRAME_MS);
            capture_restart(m);
            m->wanted = 1; /* the frame the stuck session owed */
        }
        request_frame(m); /* a failed frame, or a restart, retries */
    }
}


/*****************************************************************************/
/* HEADLESS-2 after HEADLESS-1, and HEADLESS-10 after HEADLESS-9 */
static int
mon_cmp(const void *a, const void *b)
{
    const char *na = ((const struct wlr_mon *) a)->name;
    const char *nb = ((const struct wlr_mon *) b)->name;
    size_t la = strcspn(na, "0123456789");
    size_t lb = strcspn(nb, "0123456789");
    int c = strncmp(na, nb, la < lb ? la : lb);

    if (c != 0 || la != lb)
    {
        return c != 0 ? c : (int) la - (int) lb;
    }
    return atoi(na + la) - atoi(nb + lb);
}

/*****************************************************************************/
/* connect, and check the compositor has what we need */
static void *
wlr_create(const struct wla_events *ev, void *core)
{
    struct wlr *b;
    struct wl_registry *reg;
    const char *drm;
    int i;
    int j;

    b = calloc(1, sizeof(*b));
    if (b == NULL)
    {
        return NULL;
    }
    b->ev = ev;
    b->core = core;
    b->drm_fd = -1;
    for (i = 0; i < MAX_MONS; i++)
    {
        b->mons[i].b = b;
        b->mons[i].last_ready = -1;
        for (j = 0; j < NUM_BUFS; j++)
        {
            b->mons[i].bufs[j].fd = -1;
        }
    }

    b->display = wl_display_connect(NULL);
    if (b->display == NULL)
    {
        LOG(LOG_LEVEL_ERROR, "wlr: cannot connect to the Wayland display");
        free(b);
        return NULL;
    }
    reg = wl_display_get_registry(b->display);
    wl_registry_add_listener(reg, &g_registry_listener, b);
    wl_display_roundtrip(b->display);
    wl_display_roundtrip(b->display); /* heads, output names */
    if (b->num_mons < 1 || b->seat == NULL || b->source_mgr == NULL ||
            b->copy_mgr == NULL || b->dmabuf == NULL || b->vptr_mgr == NULL ||
            b->vkbd_mgr == NULL || b->om_mgr == NULL)
    {
        LOG(LOG_LEVEL_ERROR, "wlr: compositor lacks a required protocol "
            "(output management, seat, ext-image-copy-capture, "
            "linux-dmabuf v3, wlr virtual pointer, virtual keyboard)");
        wlr_destroy(b);
        return NULL;
    }

    drm = getenv("WLXRDP_DRM");
    b->drm_fd = open(drm != NULL ? drm : "/dev/dri/renderD128",
                     O_RDWR | O_CLOEXEC);
    b->gbm = (b->drm_fd >= 0) ? gbm_create_device(b->drm_fd) : NULL;
    if (b->gbm == NULL)
    {
        /* GBM only allocates the capture buffers; encoding is the
           helper's */
        LOG(LOG_LEVEL_ERROR, "wlr: cannot open the render node for GBM");
        wlr_destroy(b);
        return NULL;
    }

    /* monitor i is the i-th output by name. Nothing holds a pointer into
       mons[] yet (listeners find monitors by name), so sorting is safe. */
    qsort(b->mons, b->num_mons, sizeof(b->mons[0]), mon_cmp);
    for (i = 0; i < b->num_mons; i++)
    {
        b->mons[i].index = i;
    }
    LOG(LOG_LEVEL_INFO, "wlr: %d output(s): first %s", b->num_mons,
        b->mons[0].name);
    b->vptr = zwlr_virtual_pointer_manager_v1_create_virtual_pointer(
                  b->vptr_mgr, b->seat);
    b->vkbd = zwp_virtual_keyboard_manager_v1_create_virtual_keyboard(
                  b->vkbd_mgr, b->seat);
    /* the virtual pointer gives the seat a pointer; the cursor sessions
       follow it */
    wl_display_roundtrip(b->display);
    b->pointer = wl_seat_get_pointer(b->seat);
    return b;
}

/*****************************************************************************/
/* wlxrdp is exiting: the compositor frees the rest with the connection */
static void
wlr_destroy(void *a)
{
    struct wlr *b = a;

    if (b == NULL)
    {
        return;
    }
    capture_stop_all(b);
    if (b->display != NULL)
    {
        wl_display_flush(b->display);
        wl_display_disconnect(b->display);
    }
    if (b->gbm != NULL)
    {
        gbm_device_destroy(b->gbm);
    }
    if (b->drm_fd >= 0)
    {
        close(b->drm_fd);
    }
    free(b);
}

/*****************************************************************************/
/* before poll: the display fd, read-prepared; wake for a cursor's hotspot
   hold */
static int
wlr_fds(void *a, struct pollfd *p, int max, int *timeout_ms)
{
    struct wlr *b = a;
    int t;

    if (max < 1)
    {
        return 0;
    }
    while (wl_display_prepare_read(b->display) != 0)
    {
        wl_display_dispatch_pending(b->display);
    }
    wl_display_flush(b->display);
    p[0].fd = wl_display_get_fd(b->display);
    p[0].events = POLLIN;
    p[0].revents = 0;
    t = wlr_cursor_timeout(b);
    if (t >= 0 && (*timeout_ms < 0 || t < *timeout_ms))
    {
        *timeout_ms = t;
    }
    return 1;
}

/*****************************************************************************/
/* after poll (every time wlr_fds was called): read and handle events */
static int
wlr_dispatch(void *a, const struct pollfd *p, int n)
{
    struct wlr *b = a;

    if (n >= 1 && (p[0].revents & POLLIN))
    {
        if (wl_display_read_events(b->display) < 0)
        {
            b->ev->lost(b->core, "Wayland connection lost");
            return -1;
        }
    }
    else
    {
        wl_display_cancel_read(b->display);
    }
    if (n >= 1 && (p[0].revents & (POLLHUP | POLLERR)) &&
            !(p[0].revents & POLLIN))
    {
        b->ev->lost(b->core, "Wayland connection lost");
        return -1;
    }
    if (wl_display_dispatch_pending(b->display) < 0)
    {
        b->ev->lost(b->core, "Wayland connection lost");
        return -1;
    }
    wlr_capture_dispatch(b);
    wlr_cursor_dispatch(b);
    return 0;
}

