/* (re)allocate the shm buffer to the current constraints */
static int
cursor_alloc(struct wlr_mon *m)
{
    struct cursor *c = &m->cur_ptr;
    struct wl_shm_pool *pool;
    int bytes;
    int fd;

    if (c->buffer != NULL)
    {
        wl_buffer_destroy(c->buffer);
        munmap(c->data, c->buf_w * c->buf_h * 4);
        c->buffer = NULL;
    }
    if (c->width <= 0 || c->height <= 0 || !c->have_argb)
    {
        return 1;
    }
    bytes = c->width * c->height * 4;
    fd = memfd_create("wlxrdp-cursor", MFD_CLOEXEC);
    if (fd < 0 || ftruncate(fd, bytes) != 0)
    {
        if (fd >= 0)
        {
            close(fd);
        }
        return 1;
    }
    c->data = mmap(NULL, bytes, PROT_READ | PROT_WRITE, MAP_SHARED, fd, 0);
    if (c->data == MAP_FAILED)
    {
        close(fd);
        return 1;
    }
    pool = wl_shm_create_pool(m->b->shm, fd, bytes);
    c->buffer = wl_shm_pool_create_buffer(pool, 0, c->width, c->height,
                                          c->width * 4,
                                          WL_SHM_FORMAT_ARGB8888);
    wl_shm_pool_destroy(pool);
    close(fd);
    c->buf_w = c->width;
    c->buf_h = c->height;
    return 0;
}

static void
cursor_request(struct wlr_mon *m)
{
    struct cursor *c = &m->cur_ptr;

    if (c->session == NULL || c->frame != NULL || c->stopped)
    {
        return;
    }
    if (c->buffer == NULL || c->buf_w != c->width || c->buf_h != c->height)
    {
        if (cursor_alloc(m) != 0)
        {
            return;
        }
    }
    c->frame_state = 1;
    c->frame = ext_image_copy_capture_session_v1_create_frame(c->session);
    ext_image_copy_capture_frame_v1_add_listener(c->frame, &g_cframe_listener,
            m);
    ext_image_copy_capture_frame_v1_attach_buffer(c->frame, c->buffer);
    ext_image_copy_capture_frame_v1_damage_buffer(c->frame, 0, 0,
            c->buf_w, c->buf_h);
    ext_image_copy_capture_frame_v1_capture(c->frame);
}

/* a cursor frame completed: keep a copy, mark it for sending */
static void
cursor_frame_done(struct wlr_mon *m)
{
    struct cursor *c = &m->cur_ptr;
    int state = c->frame_state;

    ext_image_copy_capture_frame_v1_destroy(c->frame);
    c->frame = NULL;
    c->frame_state = 0;
    if (state != 2)
    {
        return; /* failed (e.g. new constraints): the next request retries */
    }
    free(c->image);
    c->image = malloc(c->buf_w * c->buf_h * 4);
    if (c->image == NULL)
    {
        return;
    }
    memcpy(c->image, c->data, c->buf_w * c->buf_h * 4);
    c->have_image = 1;
    c->hot_pending = 0; /* the image that goes with the new hotspot */
    m->b->cursor_dirty = 1;
}

/* this output's cursor session, following the virtual pointer */
static void
cursor_start(struct wlr_mon *m)
{
    struct wlr *b = m->b;
    struct cursor *c = &m->cur_ptr;
    struct ext_image_capture_source_v1 *source;

    if (b->pointer == NULL || b->shm == NULL)
    {
        return;
    }
    memset(c, 0, sizeof(*c));
    source = ext_output_image_capture_source_manager_v1_create_source(
                 b->source_mgr, m->output);
    c->csession = ext_image_copy_capture_manager_v1_create_pointer_cursor_session(
                      b->copy_mgr, source, b->pointer);
    ext_image_capture_source_v1_destroy(source);
    ext_image_copy_capture_cursor_session_v1_add_listener(c->csession,
            &g_cursor_listener, m);
    c->session = ext_image_copy_capture_cursor_session_v1_get_capture_session(
                     c->csession);
    ext_image_copy_capture_session_v1_add_listener(c->session,
            &g_csession_listener, m);
    while (!c->constraints_done && !c->stopped)
    {
        if (wl_display_dispatch(b->display) < 0)
        {
            return;
        }
    }
    if (c->stopped || !c->have_argb)
    {
        LOG(LOG_LEVEL_WARNING, "monitor %d: no cursor capture", m->index);
        return;
    }
    cursor_request(m);
}

static void
cursor_stop(struct wlr_mon *m)
{
    struct cursor *c = &m->cur_ptr;

    if (c->frame != NULL)
    {
        ext_image_copy_capture_frame_v1_destroy(c->frame);
    }
    if (c->session != NULL)
    {
        ext_image_copy_capture_session_v1_destroy(c->session);
    }
    if (c->csession != NULL)
    {
        ext_image_copy_capture_cursor_session_v1_destroy(c->csession);
    }
    if (c->buffer != NULL)
    {
        wl_buffer_destroy(c->buffer);
        munmap(c->data, c->buf_w * c->buf_h * 4);
    }
    free(c->image);
    memset(c, 0, sizeof(*c));
    m->b->cursor_dirty = 1;
}

/* A hotspot change waits this long for its image: labwc sends the new
   hotspot, then (for a new shape) the new image; the client must never get
   the new hotspot on the old shape. */
#define HOT_HOLD_MS 50

/* After Wayland events: finished cursor frames, expired hotspot holds, and
   the active output's cursor reported to the core when it changed. */
static void
wlr_cursor_dispatch(struct wlr *b)
{
    int held = 0;
    int i;

    for (i = 0; i < b->num_mons; i++)
    {
        struct wlr_mon *m = b->mons + i;
        struct cursor *c = &m->cur_ptr;

        if (c->frame != NULL && c->frame_state >= 2)
        {
            cursor_frame_done(m);
            cursor_request(m);
        }
        if (c->hot_pending && now_ms32() - c->hot_ms >= HOT_HOLD_MS)
        {
            /* hotspot-only change: no new image is coming */
            c->hot_pending = 0;
            b->cursor_dirty = 1;
        }
        held |= c->hot_pending;
    }
    if (b->cursor_dirty && !held)
    {
        struct cursor *c = cursor_active(b);

        b->cursor_dirty = 0;
        if (c != NULL && c->have_image)
        {
            b->ev->cursor(b->core, c->image, c->buf_w, c->buf_h, c->hot_x,
                          c->hot_y);
        }
        else
        {
            b->ev->cursor(b->core, NULL, 0, 0, 0, 0);
        }
    }
}

/* when the cursor next needs a look (ms), -1: not before an event */
static int
wlr_cursor_timeout(struct wlr *b)
{
    int i;

    for (i = 0; i < b->num_mons; i++)
    {
        if (b->mons[i].cur_ptr.hot_pending)
        {
            return HOT_HOLD_MS;
        }
    }
    return -1;
}

